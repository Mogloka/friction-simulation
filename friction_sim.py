# กลุ่มแม่อึ่ง, ม. กาฟิวโคตรหล่อ
import math
 
g = 10
print("*กำหนดค่า g = 10 m/s^2, แรง f ขนานกับพื้น (+ = ดันไปข้างหน้า/ขึ้นพื้นเอียง)*")
 
choice = int(input("พื้นราบหรือพื้นเอียง <1/2>: "))
m = float(input("ใส่ค่ามวล m (kg): "))
f = float(input("ใส่ค่าแรงภายนอก f (N): "))
s = float(input("ใส่ค่าสัมประสิทธิ์ความเสียดทานสถิต: "))
j_text = input("ใส่ค่าสัมประสิทธิ์ความเสียดทานจลน์ (ไม่มีให้กด Enter): ")
j = float(j_text) if j_text != "" else s   # ถ้าโจทย์ให้ μ ค่าเดียว ใช้ค่าเดียวกัน
 
theta = 0
if choice == 2:
    theta = math.radians(float(input("องศาที่พื้นเอียงทำกับแนวระดับ: ")))
 
N = m * g * math.cos(theta)          # แรงปฏิกิริยาตั้งฉาก
F = f - m * g * math.sin(theta)      # แรงลัพธ์ก่อนคิดแรงเสียดทาน
 
if abs(F) <= s * N:
    print("วัตถุไม่เคลื่อนที่")
    print("ความเร่ง a = 0 m/s^2")
else:
    if F > 0:
        a = (F - j * N) / m          # เคลื่อนไปข้างหน้า แรงเสียดทานชี้ถอยหลัง
    else:
        a = (F + j * N) / m          # เคลื่อนถอยหลัง แรงเสียดทานชี้ไปข้างหน้า
    print("วัตถุเคลื่อนที่")
    print(f"ความเร่ง a = {a:.2f} m/s^2")